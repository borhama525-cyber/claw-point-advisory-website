import assert from 'node:assert/strict';
import { payment, remaining, calculate } from '../apps/web/src/lib/deal-math.mjs';
const near=(a,b)=>assert.ok(Math.abs(a-b)<0.001,`${a} != ${b}`);
const rows=(kind,v)=>Object.fromEntries(calculate(kind,v).map(([k,n])=>[k,n]));
near(payment(120000,0,10),1000);
near(payment(100000,6,30),599.550525);
near(payment(100000,6,30,true),500);
near(remaining(120000,0,10,5),60000);
near(remaining(120000,6,30,40),0);
const base={price:300000,closing:3,rent:2800,taxes:3600,insurance:1800,hoa:0,rate:7.5,term:30,vacancy:5,maintenance:5,capex:5,management:8,down:25,target:1.2,io:0};
const ds=rows('dscr',base);
near(ds.DSCR,2800/(payment(225000,7.5,30)+450));
near(ds['Monthly cash flow'],2800*.77-450-payment(225000,7.5,30));
near(rows('echo',{acquisition:240000,sale:300000,primary:80,closing:3,fee:2.5})['Spread after advance and fee'],-10725);
near(rows('echo',{acquisition:400000,sale:560000,primary:75,closing:2,fee:2.5})['Spread after advance and fee'],5020);
const hard={...base,rehab:50000,arv:450000,months:6,purchase:90,rehabFinanced:100,cap:70,points:2,selling:6,holding:500,rate:11};
const h=rows('hard',hard);
near(h['Loan amount'],315000);
near(rows('hard',{...hard,price:h['Breakeven purchase price']})['Estimated flip profit'],0);
const stack=rows('stack',{...base,carry:30,primary:75,fee:2.5,tc:3000,second:1200,carryRate:4,carryTerm:30,balloon:5});
near(stack['Cash required (negative = surplus)'],300);
assert.equal(rows('dscr',{...base,price:0,taxes:0,insurance:0,hoa:0}).DSCR,null);
console.log('13 financing calculation checks passed');
const sp=rows('stack',{...base,price:500000,carry:30,primary:75,fee:2.5,tc:3000,second:1200,rent:4000,taxes:3000,insurance:1500,vacancy:5,maintenance:5,capex:5,management:10,carryRate:5,carryTerm:30,balloon:5});
near(sp['Net operating income'],4000*.75-375);
near(sp['Effective income']-sp['Taxes, insurance + HOA']-sp['Maintenance + CapEx']-sp['Property management'],sp['Net operating income']);
near(sp['Monthly cash flow'],sp['Net operating income']-sp['Primary monthly payment']-sp['Seller monthly payment']);
near(sp['Cash to seller'],350000);
console.log('stack P&L checks passed');
